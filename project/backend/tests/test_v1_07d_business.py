def test_approve_all_obligations_and_counterexamples_have_independent_expectations():
    result = evaluate()
    assert result.recommendation == "recommend_approve"
    assert set(states(result).values()) == {"supported"}
    assert all(f.evidence for f in result.findings)
    assert result.observations
    # These expected outcomes are hand-authored from A, not generated by rules.
    assert (
        evaluate(order={"competitive_quote_count": 2}).recommendation
        == "recommend_conditional"
    )
    assert (
        evaluate(supplier={"procurement_status": "blocked"}).recommendation
        == "recommend_reject"
    )
    assert (
        evaluate(order={"invoice_amount_minor": None}).recommendation
        == "insufficient_information"
    )
    assert (
        evaluate(order={"invoice_currency": "USD"}).recommendation
        == "needs_human_review"
    )


