def test_blocked_and_active_are_compatible_and_missing_does_not_hide_blocking_fact():
    result = evaluate(
        supplier={
            "registry_status": "active",
            "procurement_status": "blocked",
            "tax_identifier": None,
        },
        unknown=("O-09",),
    )
    assert result.recommendation == "recommend_reject"
    assert result.conflict_pairs == ()
    assert "O-03" in result.violations and "O-09" in result.unknown_obligations
    assert next(f for f in result.findings if f.obligation_id == "O-03").missing == (
        "tax_identifier",
    )


def test_transaction_sum_invariant_and_currency_never_summed():
    split = evaluate(
        transactions=[
            {"transaction_id": "TX-1", "amount_minor": 5000},
            {"transaction_id": "TX-2", "amount_minor": 5010},
        ]
    )
    assert split.recommendation == evaluate().recommendation
    over = evaluate(
        transactions=[
            {"transaction_id": "TX-1", "amount_minor": 5000},
            {"transaction_id": "TX-2", "amount_minor": 5011},
        ]
    )
    assert over.recommendation == "recommend_reject"
    mixed = evaluate(
        transactions=[
            {"transaction_id": "TX-1", "amount_minor": 5000},
            {"transaction_id": "TX-2", "amount_minor": 999999, "currency": "USD"},
        ]
    )
    assert (
        next(f for f in mixed.findings if f.obligation_id == "O-06").reason
        == "currency_conversion_unavailable"
    )


