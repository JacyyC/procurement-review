@pytest.mark.parametrize(
    "description",
    [
        "GOLD-0004 缺合同正文",
        "GOLD-0009 专项条款",
        "海洋装备租赁新变体",
        "无任何模板词",
    ],
)
def test_procurement_has_no_contract_requirement_or_model_call(description):
    ctx = context()
    reviewed = review_procurement_v3(
        ctx, mcp_result(), authorized_scope_id=ctx.scope_id
    )
    assert (
        reviewed.source_finding.state == "supported"
        and reviewed.model_request_count == 0
    )
    result = aggregate_business_v3(
        ctx,
        document("policy", question=description),
        document(
            "contract", unknown=("O-05", "O-06", "O-08", "O-09"), question=description
        ),
        reviewed,
    )
    assert states(result)["O-03"] == "supported" and states(result)["O-05"] == "unknown"
    assert result.recommendation == "insufficient_information"


def test_model_receives_only_its_source_and_procurement_calls_are_zero():
    ctx, seen = context(), []

    async def model(request):
        seen.append(request)
        assert request.worker in {"policy", "contract"}
        assert all(s.worker == request.worker for s in request.sources)
        assert "SYN-TAX-EXISTS" not in request.model_dump_json()
        return parse_findings(json.dumps(response_body(request)), request)

    result = asyncio.run(
        review_business_v3(
            ctx,
            case_id="V107-D-0001",
            question="请核对",
            policy_sources=sources("policy"),
            contract_sources=sources("contract"),
            procurement_result=mcp_result(),
            authorized_scope_id=ctx.scope_id,
            model_branch=model,
        )
    )
    assert result.recommendation == "recommend_approve" and [
        r.worker for r in seen
    ] == ["policy", "contract"]


def test_bad_typed_extraction_is_pipeline_failure_not_guessed_business_data():
    request = document_request_v3(
        context(),
        case_id="V107-D-0001",
        worker="policy",
        question="test",
        sources=sources("policy"),
    )
    body = response_body(request, changes={"O-02": {"quotes": "3"}})
    parsed = decode_document_values(request, parse_findings(json.dumps(body), request))
    assert (
        parsed.failures == ("document_typed_value_invalid",)
        and "O-02" not in parsed.values
    )
    with pytest.raises(ValidationError):
        document_request_v3(
            context(),
            case_id="V107-D-0001",
            worker="policy",
            question="test",
            sources=sources("contract"),
        )


def test_source_scope_object_version_duplicates_fail_closed():
    ctx = context()
    for altered, scope in [
        (ctx, "OTHER"),
        (ctx.model_copy(update={"dataset_version": "v2"}), ctx.scope_id),
        (ctx.model_copy(update={"supplier_id": "OTHER"}), ctx.scope_id),
    ]:
        reviewed = review_procurement_v3(
            altered, mcp_result(), authorized_scope_id=scope
        )
        assert reviewed.failures and reviewed.order is None
    result = mcp_result()
    result = result.model_copy(update={"facts": (*result.facts, result.facts[-1])})
    assert (
        review_procurement_v3(
            ctx, result, authorized_scope_id=ctx.scope_id
        ).source_finding.state
        == "unknown"
    )


def test_five_recommendations_keep_orthogonal_reasons_and_empty_cannot_approve():
    baseline = evaluate()
    assert decide_business_v3(()).recommendation == "insufficient_information"
    combined = decide_business_v3(
        baseline.findings,
        pipeline_failures=("timeout",),
        security_events=("prompt_injection",),
        conflict_pairs=("pair-one",),
    )
    assert combined.recommendation == "needs_human_review"
    assert combined.pipeline_failures == ("timeout",) and combined.conflict_pairs == (
        "pair-one",
    )


